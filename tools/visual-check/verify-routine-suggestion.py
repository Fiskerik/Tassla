from pathlib import Path
from playwright.sync_api import sync_playwright, expect

out = Path('docs/design/evidence/gap-first-day-routine-01')
out.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 375, 'height': 844})
    page.goto('http://127.0.0.1:4179/?screen=home&state=empty&firstDay=true', wait_until='networkidle')
    page.get_by_test_id('home-open-checklist').click()
    page.get_by_role('button', name='Hantera dagens aktiviteter', exact=True).click()
    page.wait_for_timeout(500)
    page.screenshot(path=str(out / 'suggestion-375.png'))
    page.get_by_role('button', name='Använd förslaget Lugn stund som utkast').click()
    expect(page.get_by_role('textbox', name='Namn på rutin')).to_have_value('Lugn stund')
    expect(page.get_by_role('textbox', name='Checklistepunkt 1')).to_have_value('Ge plats för vila')
    page.wait_for_timeout(300)
    assert page.evaluate('window.__homeFirstDayMutationCounts.createCalls') == 0
    page.get_by_role('button', name='Tillbaka', exact=True).click()
    expect(page.get_by_text('Lämna utan att spara?', exact=True)).to_be_visible()
    page.get_by_role('button', name='Fortsätt redigera').click()
    expect(page.get_by_role('textbox', name='Namn på rutin')).to_have_value('Lugn stund')
    page.get_by_role('textbox', name='Checklistepunkt 1').fill('Egen lugn stund')
    page.screenshot(path=str(out / 'editable-draft-375.png'))
    page.get_by_role('button', name='Spara rutin', exact=True).click()
    expect(page.get_by_text('Lugn stund', exact=True)).to_be_visible()
    assert page.evaluate('window.__homeFirstDayMutationCounts.createCalls') == 1
    page.get_by_role('button', name='Klar', exact=True).click()
    expect(page.get_by_role('checkbox', name='Rutin Lugn stund, punkt Egen lugn stund, inte klar')).to_be_visible()
    page.goto('http://127.0.0.1:4179/?screen=checklist&state=empty&firstDay=true', wait_until='networkidle')
    page.get_by_role('button', name='Hantera dagens aktiviteter', exact=True).click()
    page.get_by_role('button', name='Använd förslaget Lugn stund som utkast').click()
    expect(page.get_by_role('textbox', name='Namn på rutin')).to_have_value('Lugn stund')
    page.goto('http://127.0.0.1:4179/?screen=home&state=empty&firstDay=true&firstDayAdd=unknown', wait_until='networkidle')
    page.get_by_test_id('home-open-checklist').click()
    page.get_by_role('button', name='Hantera dagens aktiviteter', exact=True).click()
    page.get_by_role('button', name='Använd förslaget Lugn stund som utkast').click()
    page.get_by_role('button', name='Spara rutin', exact=True).click()
    expect(page.get_by_text('Rutinen sparades, men vi kunde inte bekräfta om den lades till på den valda dagen. Kontrollera samma ändring innan du fortsätter.', exact=True)).to_be_visible()
    before = page.evaluate('window.__homeFirstDayMutationCounts')
    page.get_by_role('button', name='Kontrollera samma ändring igen', exact=True).click()
    expect(page.get_by_role('button', name='Kontrollera samma ändring igen', exact=True)).to_have_count(0)
    after = page.evaluate('window.__homeFirstDayMutationCounts')
    assert before['createCalls'] == after['createCalls'] == 1
    assert before['mutationId'] == after['mutationId'] and after['dayAddCalls'] == 2
    page.goto('http://127.0.0.1:4179/?screen=home&state=empty&firstDay=true&firstDayAdd=failed', wait_until='networkidle')
    page.get_by_test_id('home-open-checklist').click()
    page.get_by_role('button', name='Hantera dagens aktiviteter', exact=True).click()
    page.get_by_role('button', name='Använd förslaget Lugn stund som utkast').click()
    page.get_by_role('button', name='Spara rutin', exact=True).click()
    expect(page.get_by_text('Rutinen sparades, men den kunde inte läggas till på den valda dagen. Öppna Checklistor och lägg till den från rutinhallen.', exact=True)).to_be_visible()
    page.get_by_role('button', name='Klar', exact=True).click()
    expect(page.get_by_role('checkbox')).to_have_count(0)
    browser.close()
print('PASS: editable suggestion, explicit save, both entrances and day-selection recovery')
