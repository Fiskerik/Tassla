"""Synthetic catalog responses through the real Development catalog component and validator."""
import json, os, re
from pathlib import Path
from playwright.sync_api import expect, sync_playwright

base = os.environ.get('TASSLA_UI_BASE_URL', 'http://127.0.0.1:5435').rstrip('/')
out = Path(os.environ.get('TASSLA_UI_EVIDENCE', 'docs/design/evidence/development-content-01'))
out.mkdir(parents=True, exist_ok=True)
results, errors = [], []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox', '--disable-dev-shm-usage'])
    page = browser.new_page(viewport={'width': 375, 'height': 844})
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(base + '/probe/')
    row = page.get_by_test_id('development-phase-item-name')
    expect(row).to_contain_text('· A')
    expect(page.get_by_role('link', name=re.compile('Öppna källa:'))).not_to_have_count(0)
    page.get_by_role('tab', name='Före hemkomst', exact=True).click()
    expect(page.get_by_test_id('development-phase-item-safe-space')).to_be_visible()
    page.get_by_role('tab', name='Första dagarna', exact=True).click()
    expect(page.get_by_test_id('development-phase-item-quiet-start')).to_be_visible()
    page.get_by_role('tab', name='Utifrån ålder', exact=True).click()
    expect(row).to_contain_text('· A')
    results.append('Actual catalog: age and two explicit contexts show validated suggestions and source links')

    page.get_by_role('button', name='Ladda långsamt', exact=True).click()
    expect(row).to_have_count(0)
    page.get_by_test_id('development-phase-suggestions').scroll_into_view_if_needed()
    page.screenshot(path=str(out / 'synthetic-phase-loading-375.png'))
    page.get_by_role('button', name='Byt klient', exact=True).click()
    expect(row).to_contain_text('· A-new')
    page.get_by_role('button', name='Släpp sena svar', exact=True).click()
    page.wait_for_timeout(100)
    expect(row).to_contain_text('· A-new')
    results.append('Client change immediately hides prior catalog and ignores late responses')

    page.get_by_role('button', name='Simulera fasfel', exact=True).click()
    expect(page.get_by_text('Förslagen kunde inte hämtas.', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Öppna: En lugn start')).to_be_visible()
    page.get_by_text('Förslagen kunde inte hämtas.', exact=True).scroll_into_view_if_needed()
    page.screenshot(path=str(out / 'synthetic-phase-error-375.png'))
    page.get_by_role('button', name='Öppna: En lugn start').scroll_into_view_if_needed()
    page.screenshot(path=str(out / 'synthetic-reading-ready-375.png'))
    page.get_by_role('button', name='Hämta fasförslag igen', exact=True).click()
    expect(row).to_contain_text('· A-error')
    page.get_by_role('button', name='Växla läsfel', exact=True).click()
    expect(page.get_by_text('Rekommendationerna kunde inte hämtas just nu.', exact=True)).to_be_visible()
    expect(row).to_be_visible()
    page.get_by_text('Rekommendationerna kunde inte hämtas just nu.', exact=True).scroll_into_view_if_needed()
    page.screenshot(path=str(out / 'synthetic-reading-error-375.png'))
    page.get_by_role('button', name='Hämta rekommenderad läsning igen', exact=True).click()
    page.get_by_role('button', name='Simulera tom fas', exact=True).click()
    empty = page.get_by_text('Det finns inga publicerade förslag för valet just nu.', exact=True)
    expect(empty).to_be_visible(); empty.scroll_into_view_if_needed()
    page.screenshot(path=str(out / 'synthetic-phase-empty-375.png'))
    page.get_by_role('button', name='Återställ klient', exact=True).click()
    expect(row).to_contain_text('· A-recovered')
    results.append('Phase retry and reading errors are independent')

    page.get_by_role('button', name='Ladda långsamt', exact=True).click()
    page.get_by_role('button', name='Byt hund', exact=True).click()
    expect(row).to_contain_text('· B')
    page.get_by_role('button', name='Släpp sena svar', exact=True).click()
    page.wait_for_timeout(100)
    expect(row).to_contain_text('· B')
    page.get_by_role('button', name='Ladda långsamt', exact=True).click()
    page.get_by_role('button', name='Byt konto', exact=True).click()
    expect(row).to_contain_text('· owner-B')
    page.get_by_role('button', name='Släpp sena svar', exact=True).click()
    page.wait_for_timeout(100)
    expect(row).to_contain_text('· owner-B')
    results.append('Dog and owner changes discard late responses from former scope')

    page.get_by_role('button', name='Ladda långsamt', exact=True).click()
    page.get_by_role('button', name='Visa eller stäng vy', exact=True).click()
    expect(page.get_by_test_id('development-screen')).to_have_count(0)
    page.get_by_role('button', name='Släpp sena svar', exact=True).click()
    page.get_by_role('button', name='Byt klient', exact=True).click()
    page.get_by_role('button', name='Visa eller stäng vy', exact=True).click()
    expect(row).to_contain_text('· B-new')
    page.get_by_role('button', name='Öppna: En lugn start', exact=True).click()
    page.get_by_role('button', name='Tillbaka från published-v1', exact=True).click()
    expect(row).to_contain_text('· B-new')
    results.append('Leaving/unmounting ignores late catalog; published-version reading can return')
    page.close()

    for width, height, large in [(375, 844, False), (430, 844, False), (375, 667, False), (375, 667, True)]:
        page = browser.new_page(viewport={'width': width, 'height': height})
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(base + '/app/?screen=development')
        page.wait_for_timeout(500)
        if large:
            page.evaluate("""() => document.querySelectorAll('[dir=auto]').forEach(el => {
              const s = getComputedStyle(el), f = parseFloat(s.fontSize), l = parseFloat(s.lineHeight);
              if (Number.isFinite(f)) el.style.fontSize = `${f*1.4}px`;
              if (Number.isFinite(l)) el.style.lineHeight = `${l*1.4}px`;
            })""")
        target = page.get_by_test_id('development-phase-suggestions')
        target.scroll_into_view_if_needed()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        suffix = f'{width}x{height}' + ('-text140' if large else '')
        page.screenshot(path=str(out / f'development-{suffix}.png'))
        results.append(f'{suffix}: phase card displayed without horizontal overflow (synthetic fixture)')
        page.close()
    browser.close()
assert not errors, errors
(out / 'results.json').write_text(json.dumps({'results': results, 'page_errors': errors,
 'limits': 'Synthetic published-shaped catalog responses. Live publication, RLS and native device behavior not verified.'}, ensure_ascii=False, indent=2) + '\n')
print('\n'.join(results))
