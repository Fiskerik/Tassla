"""Synthetic RNWeb checks for confirmed, pending and reversible training completion."""
import json
import os
import re
from pathlib import Path
from playwright.sync_api import expect, sync_playwright

base = os.environ['TASSLA_UI_BASE_URL'].rstrip('/')
out = Path('docs/design/evidence/training-completion-01')
out.mkdir(parents=True, exist_ok=True)
errors, results = [], []

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox', '--disable-dev-shm-usage'])
    for width, height, large in [(375,844,False), (430,844,False), (375,667,True)]:
        page = browser.new_page(viewport={'width':width,'height':height})
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(base+'/?screen=training&trainingScenario=unstarted&progression=complete')
        expect(page.locator('[role="progressbar"][aria-label="3 av 3 delmål bekräftade"]')).to_be_attached()
        if width==375 and not large: page.screenshot(path=str(out/'recommended-375x844.png'))
        page.get_by_role('tab',name='Alla övningar').click()
        card=page.get_by_role('button',name=re.compile('^Trygg vardagsstart, Pågår,'))
        expect(card).to_contain_text('3 av 3 delmål bekräftade')
        if large:
            page.evaluate('''() => document.querySelectorAll('[dir=auto]').forEach(e=>{let s=getComputedStyle(e);e.style.fontSize=parseFloat(s.fontSize)*1.4+'px';if(s.lineHeight!=='normal')e.style.lineHeight=parseFloat(s.lineHeight)*1.4+'px'})''')
        page.screenshot(path=str(out/(f'list-{width}x{height}'+('-text140' if large else '')+'.png')))
        card.click()
        if large:
            page.evaluate('''() => document.querySelectorAll('[dir=auto]').forEach(e=>{let s=getComputedStyle(e);e.style.fontSize=parseFloat(s.fontSize)*1.4+'px';if(s.lineHeight!=='normal')e.style.lineHeight=parseFloat(s.lineHeight)*1.4+'px'})''')
        expect(page.get_by_text('Alla delmål bekräftade',exact=True)).to_be_visible()
        expect(page.get_by_role('button',name='Visa alla träningsprogram')).to_be_visible()
        page.screenshot(path=str(out/(f'overview-{width}x{height}'+('-text140' if large else '')+'.png')))
        page.get_by_role('button',name='Öppna aktivt steg: Vila nära').scroll_into_view_if_needed()
        expect(page.get_by_role('button',name='Öppna aktivt steg: Vila nära')).to_be_in_viewport()
        page.get_by_role('button',name='Visa alla träningsprogram').click()
        expect(page.get_by_role('tab',name='Alla övningar')).to_be_visible()
        page.get_by_role('button',name=re.compile('^Trygg vardagsstart, Pågår,')).click()
        page.get_by_role('button',name='Öppna aktivt steg: Vila nära').click()
        modal=page.get_by_test_id('center-modal-bottom-sheet')
        modal.get_by_role('button',name='Ångra färdigmarkering för Vila nära').click()
        expect(modal.get_by_role('button',name='Ångra färdigmarkering för Vila nära')).to_have_count(0)
        modal.get_by_role('button',name='Stäng',exact=True).click()
        page.get_by_role('button',name='Tillbaka',exact=True).click()
        expect(page.get_by_role('button',name=re.compile('^Trygg vardagsstart,'))).to_contain_text('2 av 3 delmål bekräftade')
        expect(page.get_by_text('Alla delmål bekräftade',exact=True)).to_have_count(0)
        results.append(f'{width}x{height}: complete, navigation and undo')
        page.close()
    for state, expected in [('pending','Sparar'),('unknown','Kontrolleras')]:
        page=browser.new_page(viewport={'width':375,'height':844})
        page.goto(base+f'/?screen=training&trainingScenario=unstarted&progression=complete&completionPending={state}')
        expect(page.get_by_text('Alla delmål bekräftade',exact=True)).to_have_count(0)
        page.get_by_role('tab',name='Alla övningar').click()
        card=page.get_by_role('button',name=re.compile('^Trygg vardagsstart,'))
        expect(card).to_contain_text(expected)
        expect(card.get_by_text('Alla delmål bekräftade',exact=True)).to_have_count(0)
        card.click()
        expect(page.get_by_text('Alla delmål bekräftade',exact=True)).to_have_count(0)
        expect(page.get_by_test_id('training-journey-timeline')).to_have_count(0)
        page.screenshot(path=str(out/f'{state}-375.png'))
        results.append(state+': no confirmed completion')
        page.close()
    page=browser.new_page(viewport={'width':375,'height':844})
    page.goto(base+'/?screen=training&trainingScenario=unstarted&progression=complete-paused')
    page.get_by_role('tab',name='Alla övningar').click()
    expect(page.get_by_role('button',name=re.compile('^Trygg vardagsstart, Pausad,'))).to_be_visible()
    results.append('paused: state preserved')
    page.close()
    page=browser.new_page(viewport={'width':375,'height':844})
    page.goto(base+'/?screen=training&trainingScenario=unstarted&progression=complete&progressionRead=error')
    expect(page.get_by_text('Fortsätt där ni var',exact=True)).to_have_count(0)
    expect(page.get_by_text('Alla delmål bekräftade',exact=True)).to_have_count(0)
    page.get_by_role('tab',name='Alla övningar').click()
    card=page.get_by_role('button',name=re.compile('^Trygg vardagsstart,'))
    expect(card).to_contain_text('Otillgänglig')
    expect(card).not_to_contain_text('Ej påbörjad')
    expect(page.get_by_role('button',name='Hämta träningsresan igen')).to_be_visible()
    page.get_by_role('tab',name='Mina').click()
    expect(page.get_by_text('Inga sparade träningsresor eller aktivitetsmarkeringar ännu')).to_have_count(0)
    expect(page.get_by_role('button',name=re.compile('^Trygg vardagsstart,'))).to_contain_text('Otillgänglig')
    expect(page.get_by_role('button',name='Hämta träningsresan igen')).to_be_visible()
    results.append('read error: no invented empty or unstarted status; retry offered')
    page.close()
    page=browser.new_page(viewport={'width':375,'height':844})
    page.goto(base+'/?screen=training&trainingScenario=unstarted&progressionWrite=unknown-before-retry')
    page.get_by_role('tab',name='Alla övningar').click()
    page.get_by_role('button',name=re.compile('^Trygg vardagsstart,')).click()
    page.get_by_role('button',name=re.compile('^Starta träningsresa')).click()
    page.get_by_role('button',name='Kontrollera samma träningsändring igen').click()
    expect(page.get_by_test_id('center-modal-bottom-sheet')).to_be_visible()
    expect(page.get_by_role('button',name='Hämta träningsresan igen')).to_have_count(0)
    ops=page.evaluate('window.__tasslaTrainingProgressionOperations')
    assert len(ops)==2 and ops[0]['operationId']==ops[1]['operationId'],ops
    results.append('unknown already refreshed: same operation retry opens verified step')
    page.close()
    browser.close()
assert not errors, errors
(out/'results.json').write_text(json.dumps({'results':results,'page_errors':errors,'limits':'Synthetic RNWeb; enlarged CSS is not native Dynamic Type; live/RLS untested.'},ensure_ascii=False,indent=2)+'\n')
print('\n'.join(results))
